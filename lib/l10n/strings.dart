/// Supported UI languages.
const List<String> kLanguages = ['en', 'tr', 'ar'];

/// Translates [english] into [code]; unknown phrases and 'en' come back unchanged.
String translate(String code, String english) =>
    kTranslations[code]?[english] ?? english;

/// Translates a template and fills {0}, {1}… with [args].
String fmt(String code, String template, List<Object> args) {
  var s = translate(code, template);
  for (var i = 0; i < args.length; i++) {
    s = s.replaceAll('{$i}', '${args[i]}');
  }
  return s;
}
